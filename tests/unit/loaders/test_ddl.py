def test_parse_errors_report_their_position() -> None:
    with pytest.raises(LoadError, match=r"line 2, column \d+: .* near 'KEY'"):
        load_ddl("CREATE TABLE t (a int,\n b int PRIMARY KEY KEY);", PG)


def test_load_ddl_file(tmp_path: Path) -> None:
    path = tmp_path / "schema.sql"
    path.write_text("CREATE TABLE t (a int);", encoding="utf-8")

    assert load_ddl_file(path, PG).schema == Schema((Table("t", (Column("a", INTEGER),)),))


def test_load_ddl_file_errors_name_the_file(tmp_path: Path) -> None:
    path = tmp_path / "broken.sql"
    path.write_text("CREATE TABLE t (a int PRIMARY KEY KEY);", encoding="utf-8")

    with pytest.raises(LoadError, match=r"broken\.sql: line 1"):
        load_ddl_file(path, PG)
    with pytest.raises(LoadError, match=r"cannot read .*missing\.sql"):
        load_ddl_file(tmp_path / "missing.sql", PG)


