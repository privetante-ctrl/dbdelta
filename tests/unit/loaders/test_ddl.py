@pytest.mark.parametrize(
    "statement",
    [
        "CREATE INDEX ix ON audit.t (a)",
        "CREATE TYPE audit.mood AS ENUM ('ok')",
        "ALTER TABLE audit.t ADD COLUMN b int",
        "DROP TABLE audit.t",
    ],
)
def test_statements_on_other_schemas_are_skipped(statement: str) -> None:
    result = load_ddl(f"CREATE TABLE t (a int); {statement}", PG)

    assert result.schema == load_ddl("CREATE TABLE t (a int)", PG).schema
    assert result.warnings[0].endswith("only objects in schema 'public' are loaded")


def test_empty_statements_are_ignored() -> None:
    assert load_ddl(";; CREATE TABLE t (a int);;", PG).schema.tables[0].name == "t"


def test_long_statements_are_shortened_in_warnings() -> None:
    columns = ", ".join(f"column_{number} int" for number in range(20))
    result = load_ddl(f"CREATE TEMP TABLE t ({columns})", PG)

    snippet = result.warnings[0].removeprefix("skipped ").split(":")[0]
    assert len(snippet) == 70
    assert snippet.endswith("...")


