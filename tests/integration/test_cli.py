@pytest.mark.postgres
def test_a_live_postgresql_database_is_compared(postgres: psycopg.Connection) -> None:
    postgres.execute((MIXED / "a.sql").read_text(encoding="utf-8"))
    row = postgres.execute("SELECT current_schema()").fetchone()
    assert row is not None

    result = run("plan", os.environ[POSTGRES_URL_VARIABLE], "b.sql", "--schema", row[0])

    # The database knows the names it gave constraints, so only the comments differ.
    assert result.exit_code == 0, result.output
    expected = (MIXED / f"expected.{Dialect.POSTGRESQL}.sql").read_text(encoding="utf-8")
    assert _statements(result.stdout) == _statements(expected)


def _statements(sql: str) -> list[str]:
    return [line for line in sql.splitlines() if line and not line.startswith("--")]
