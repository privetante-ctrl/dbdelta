def test_databases_of_different_dialects_are_an_error() -> None:
    result = run("diff", "postgresql://db/app", "sqlite:///app.db")

    assert result.exit_code == EXIT_USAGE
    assert "both sides must use one dialect" in result.stderr


def test_a_live_sqlite_database_can_be_either_side(tmp_path: Path) -> None:
    database = tmp_path / "app.db"
    with closing(sqlite3.connect(database)) as connection:
        connection.executescript((MIXED / "a.sql").read_text(encoding="utf-8"))
        connection.execute("CREATE VIEW names AS SELECT name FROM players")

    result = run("plan", f"sqlite:///{database}", "b.sql")

    assert result.exit_code == 0
    assert result.stdout.endswith((MIXED / "expected.sqlite.sql").read_text(encoding="utf-8"))
    assert result.stderr == (
        f"warning: sqlite:///{database}: skipped view 'names': it is not supported\n"
    )


@pytest.mark.parametrize("output_format", ["text", "markdown"])
def test_reports_list_what_was_not_compared(tmp_path: Path, output_format: str) -> None:
    source = tmp_path / "views.sql"
    source.write_text("CREATE VIEW v AS SELECT 1;", encoding="utf-8")

    result = run("diff", source, "b.sql", "--format", output_format)

    assert "CREATE VIEW is not supported" in result.stdout
    # Only formats that are not the text report repeat warnings on stderr.
    assert (result.stderr == "") is (output_format == "text")


