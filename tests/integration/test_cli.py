@pytest.fixture(autouse=True)
def workspace(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """Run in a directory holding the mixed pair, with output independent of the terminal.

    Relative paths keep the snapshots the same on every machine.
    """
    for variable in ("FORCE_COLOR", "NO_COLOR", "TTY_COMPATIBLE", "TTY_INTERACTIVE"):
        monkeypatch.delenv(variable, raising=False)
    monkeypatch.setenv("COLUMNS", "100")
    for name in ("a.sql", "b.sql"):
        shutil.copy(MIXED / name, tmp_path / name)
    monkeypatch.chdir(tmp_path)


def run(*args: str | Path) -> Result:
    return CliRunner().invoke(app, [str(arg) for arg in args])


def mixed(command: str, *options: str | Path) -> Result:
    return run(command, "a.sql", "b.sql", *options)


def without_version(text: str) -> str:
    return text.replace(__version__, "<version>")


def test_diff_reports_changes_and_risks(snapshot: Snapshot) -> None:
    result = mixed("diff")

    assert result.exit_code == 0
    assert result.stderr == ""
    snapshot(SNAPSHOTS / "diff.txt", without_version(result.stdout))


def test_plan_prints_the_migration_with_a_header() -> None:
    result = mixed("plan")

    assert result.exit_code == 0
    header, _, script = result.stdout.partition("\n\n")
    assert header.startswith("-- Migration from a.sql to b.sql (postgresql), generated by")
    assert script == (MIXED / "expected.postgresql.sql").read_text(encoding="utf-8")


def test_plan_for_sqlite() -> None:
    result = mixed("plan", "--dialect", "sqlite")

    assert result.exit_code == 0
    assert result.stdout.endswith((MIXED / "expected.sqlite.sql").read_text(encoding="utf-8"))


def test_check_fails_on_dangerous_changes() -> None:
    result = mixed("check")

    assert result.exit_code == EXIT_CHECK_FAILED
    assert result.stdout.rstrip().endswith(
        "Check failed: 2 dangerous changes. Review them, then rerun with --allow-destructive "
        "to accept them."
    )


def test_check_passes_when_destruction_is_allowed() -> None:
    result = mixed("check", "--allow-destructive")

    assert result.exit_code == 0
    assert "Check passed: 2 dangerous changes allowed by --allow-destructive." in result.stdout


def test_check_passes_without_dangerous_changes() -> None:
    result = run("check", CREATE / "a.sql", CREATE / "b.sql")

    assert result.exit_code == 0
    assert "Check passed: no dangerous changes." in result.stdout


def test_check_reports_its_verdict_on_stderr_for_machine_formats() -> None:
    result = mixed("check", "--format", "json")

    assert result.exit_code == EXIT_CHECK_FAILED
    assert json.loads(result.stdout)["check"] == {
        "passed": False,
        "allow_destructive": False,
        "dangers": 2,
    }
    assert result.stderr.startswith("Check failed: 2 dangerous changes.")


def test_markdown_report(snapshot: Snapshot) -> None:
    result = mixed("check", "--format", "markdown")

    snapshot(SNAPSHOTS / "check.md", without_version(result.stdout))


def test_json_report(snapshot: Snapshot) -> None:
    result = mixed("diff", "--format", "json")
    report = json.loads(result.stdout)

    assert report["summary"] == {"changes": 16, "danger": 2, "warning": 6, "info": 0}
    for finding in report["findings"]:
        assert all(report["changes"][index]["risk"] for index in finding["changes"])
    snapshot(SNAPSHOTS / "diff.json", without_version(result.stdout))


def test_identical_schemas() -> None:
    same = "b.sql"

    assert "No changes: the schemas are identical." in run("diff", same, same).stdout
    assert run("plan", same, same).stdout.endswith("-- No changes: the schemas are identical.\n")


def test_output_goes_to_a_file_and_status_to_stderr(tmp_path: Path) -> None:
    output = tmp_path / "migration.sql"

    result = mixed("plan", "--output", output)

    assert result.exit_code == 0
    assert result.stdout == ""
    assert result.stderr == (
        f"Wrote the migration to {output}. 16 changes, 8 risks: 2 danger, 6 warning.\n"
    )
    assert output.read_text(encoding="utf-8").endswith("COMMIT;\n")


def test_text_written_to_a_file_has_no_colors_even_when_forced(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("FORCE_COLOR", "1")
