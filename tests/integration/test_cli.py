def test_names_are_never_read_as_rich_markup(tmp_path: Path) -> None:
    source = tmp_path / "a.sql"
    target = tmp_path / "b.sql"
    source.write_text("", encoding="utf-8")
    target.write_text('CREATE TABLE "[bold]x[/bold]" (id int);', encoding="utf-8")

    result = run("diff", source, target)

    assert "create table [bold]x[/bold]" in result.stdout


def test_ignored_tables_and_rules_are_left_out() -> None:
    result = mixed(
        "check",
        "--ignore-table",
        "legacy_*",
        "--ignore-rule",
        "drop-column",
        "--format",
        "json",
    )
    report = json.loads(result.stdout)

    assert result.exit_code == 0
    assert "drop table legacy_scores" not in [change["description"] for change in report["changes"]]
    assert {finding["rule"] for finding in report["findings"]} == {
        "check-violations",
        "foreign-key",
        "index-lock",
        "set-not-null",
        "type-rewrite",
    }


def test_an_unknown_rule_is_a_usage_error() -> None:
    result = mixed("diff", "--ignore-rule", "drop-colum")

    assert result.exit_code == EXIT_USAGE
    assert result.stderr.startswith("error: unknown risk rule(s): drop-colum; the rules are: ")


def test_settings_come_from_dbdelta_toml(tmp_path: Path) -> None:
    (tmp_path / "dbdelta.toml").write_text(
        'dialect = "sqlite"\nallow-destructive = true\n', encoding="utf-8"
    )

    result = mixed("check", "--format", "sql")

    assert result.exit_code == 0
    assert "PRAGMA foreign_keys = OFF;" in result.stdout


def test_options_override_dbdelta_toml(tmp_path: Path) -> None:
    (tmp_path / "dbdelta.toml").write_text("allow-destructive = true\n", encoding="utf-8")

    assert mixed("check").exit_code == 0
    assert mixed("check", "--no-allow-destructive").exit_code == EXIT_CHECK_FAILED


